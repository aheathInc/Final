import { Router } from 'express';
import { createAuthGuards,createIdempotency,createTokenService } from '@a-health/http';
import { env } from '../config/env.js';
import * as c from '../controllers/payment.controller.js';
const {requireAuth}=createAuthGuards(createTokenService({secret:env.JWT_SECRET,issuer:env.JWT_ISSUER,audience:env.JWT_AUDIENCE,ttlSeconds:env.ACCESS_TOKEN_TTL_SECONDS}));
const idempotency=createIdempotency(env.IDEMPOTENCY_TTL_HOURS);
export const paymentRouter=Router();
paymentRouter.use('/payments',(_req,res,next)=>{res.setHeader('Cache-Control','no-store');next();});
paymentRouter.post('/payments/provider/flutterwave',c.flutterwaveWebhook);
paymentRouter.post('/payments/webhooks/:provider',c.webhook);
paymentRouter.get('/payments/options',requireAuth,c.options);
paymentRouter.get('/payments/bills',requireAuth,c.listBills);
paymentRouter.get('/payments/bills/:bill_id/receipt',requireAuth,c.downloadBillReceipt);
paymentRouter.post('/payments/bills',requireAuth,idempotency,c.issueBill);
paymentRouter.post('/payments/intents',requireAuth,idempotency,c.createIntent);
paymentRouter.get('/payments/intents/:payment_intent_id',requireAuth,c.getIntent);
paymentRouter.post('/payments/intents/:payment_intent_id/cancel',requireAuth,idempotency,c.cancelIntent);
paymentRouter.get('/payments',requireAuth,c.listPayments);
paymentRouter.post('/payments/:payment_id/refund',requireAuth,idempotency,c.refund);
