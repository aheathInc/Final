from playwright.sync_api import sync_playwright
from pathlib import Path
import json, datetime, argparse, os
parser = argparse.ArgumentParser(description="Actual AHP component preview checks with synthetic data; no backend or login.")
parser.add_argument("--html", type=Path, default=Path(__file__).resolve().parents[1] / "demo-previews/AHP_Care_Continuity_Preview_006.html")
parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "Web/.local/care-preview-checks")
parser.add_argument("--no-sandbox", action="store_true", help="Only for a separately approved root/container browser test environment")
args = parser.parse_args()
out=args.out.resolve();out.mkdir(parents=True,exist_ok=True)
results=[]
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=os.environ.get('AHP_CHROMIUM_EXECUTABLE'),headless=True,args=['--no-sandbox'] if args.no_sandbox else [])
 page=b.new_page(viewport={'width':1440,'height':1080},device_scale_factor=1)
 page.set_default_timeout(5000)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 # In-memory rendering only; no file/HTTP browser navigation or policy changes.
 page.set_content(args.html.resolve().read_text(encoding='utf-8'),wait_until='load')
 page.get_by_role('button',name='Patient A · Demo').wait_for()
 results.append({'check':'actual TSX component mounts against explicitly synthetic preview transport','pass':True})
 page.screenshot(animations='disabled',path=str(out/'care-worklist-desktop.png'),full_page=True)
 page.get_by_role('button',name='Patient A · Demo').click()
 page.get_by_role('heading',name='Check-ins & clinical review').wait_for()
 page.screenshot(animations='disabled',path=str(out/'care-review-desktop.png'),full_page=True)
 page.get_by_label('Review note').fill('TEST DATA ONLY — reviewed in synthetic preview')
 page.get_by_role('button',name='Record review',exact=True).click()
 page.get_by_text('Check-in review recorded. No recovery outcome was inferred.').wait_for()
 results.append({'check':'review action updates assigned worklist and preserves explicit outcome semantics','pass':True})
 page.get_by_role('button',name='Patient B · Demo').click()
 page.get_by_role('tab',name='Medication timing').click()
 tomorrow=(datetime.datetime.now()+datetime.timedelta(days=1)).strftime('%Y-%m-%d')
 page.get_by_label('Agreed start date').fill(tomorrow)
 page.get_by_label('Time zone',exact=True).fill('Africa/Dar_es_Salaam')
 page.get_by_label('Daily times').fill('08:00, 20:00')
 page.get_by_role('button',name='Save reminder times').click()
 page.get_by_text('Clinician-selected reminder times saved.').wait_for()
 page.get_by_text('08:00 · 20:00').wait_for()
 results.append({'check':'explicit schedule submit, refresh and read-back through preview transport','pass':True})
 page.screenshot(animations='disabled',path=str(out/'care-schedule-desktop.png'),full_page=True)
 page.get_by_role('button',name='Pause reminders').click()
 page.get_by_role('button',name='Resume reminders').wait_for()
 results.append({'check':'pause/resume control reflects persisted preview response','pass':True})
 page.get_by_role('tab',name='Contact & follow-up').click()
 page.get_by_label('Date & time').fill(tomorrow+'T09:30')
 page.get_by_label('Purpose').fill('TEST DATA ONLY — check progress')
 page.get_by_role('button',name='Schedule contact').click()
 page.get_by_text('Contact scheduled. A phone call has not been placed.').wait_for()
 results.append({'check':'contact scheduling does not claim call placement','pass':True})
 page.screenshot(animations='disabled',path=str(out/'care-contacts-desktop.png'),full_page=True)
 page.get_by_role('button',name='Dark appearance').click()
 page.screenshot(animations='disabled',path=str(out/'care-dark-desktop.png'),full_page=True)
 page.get_by_role('button',name='Compact view').click()
 results.append({'check':'density toggle applies compact class','pass':page.locator('.care-workspace').evaluate('(e)=>e.classList.contains("care-compact")')})
 page.get_by_role('button',name='Switch to Doctor B').click()
 page.get_by_text('No active cycles.').wait_for()
 assert page.get_by_role('heading',name='Patient A · Demo').count()==0
 results.append({'check':'owner change clears previous clinical detail and worklist','pass':True})
 page.get_by_role('button',name='Switch to Doctor A').click()
 page.get_by_role('button',name='Patient A · Demo').wait_for()
 page.get_by_role('button',name='Test service error').click()
 page.get_by_role('button',name='Refresh worklist').click()
 page.get_by_role('alert').wait_for()
 assert page.get_by_text('No active cycles.').count()==0
 results.append({'check':'service error is not rendered as successful empty state','pass':True})
 page.screenshot(animations='disabled',path=str(out/'care-error-desktop.png'),full_page=True)
 page.get_by_role('button',name='Restore preview service').click()
 page.get_by_role('button',name='Reload',exact=True).click()
 page.get_by_role('button',name='Patient A · Demo').wait_for()
 for width in (1440,1024,768,390):
  page.set_viewport_size({'width':width,'height':900})
  page.get_by_role('button',name='Patient B · Demo').click()
  page.get_by_role('tab',name='Clinical review').wait_for()
  overflow=page.evaluate('document.documentElement.scrollWidth > window.innerWidth')
  results.append({'check':f'no horizontal page overflow at {width}px','pass':not overflow})
  page.screenshot(animations='disabled',path=str(out/f'care-{width}-dark.png'),full_page=True)
 page.get_by_role('button',name='Light appearance').click()
 page.screenshot(animations='disabled',path=str(out/'care-390-light.png'),full_page=True)
 page.emulate_media(reduced_motion='reduce')
 transition=page.locator('.care-button').first.evaluate('(el)=>getComputedStyle(el).transitionDuration')
 results.append({'check':'reduced-motion disables transitions','pass':transition=='0s','actual':transition})
 page.set_viewport_size({'width':1440,'height':1080})
 page.get_by_role('tab',name='Clinical review').focus()
 page.keyboard.press('ArrowRight')
 results.append({'check':'tab arrow key changes focus and selected panel','pass':page.get_by_role('tab',name='Medication timing').get_attribute('aria-selected')=='true'})
 page.get_by_role('link',name='Medication schedules',exact=True).click()
 page.get_by_role('heading',name='Agree the times. Keep care connected.').wait_for()
 page.screenshot(animations='disabled',path=str(out/'medication-independent-desktop.png'),full_page=True)
 results.append({'check':'actual medication planner opens without a follow-up-cycle dependency','pass':True})
 results.append({'check':'browser page errors','pass':not errors,'errors':errors})
 b.close()
Path('/mnt/data/ahp-implementation-006/browser-evidence/results.json').write_text(json.dumps({'kind':'actual-component browser with synthetic in-memory preview API; not live AHP/Next/Auth E2E','checks':results},indent=2))
print(json.dumps(results,indent=2))
assert all(x['pass'] for x in results)
